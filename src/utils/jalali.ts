/**
 * Pure zero-dependency Gregorian <-> Jalali (Solar Hijri) astronomical arithmetic module.
 * Verified across 1900–2100 including leap years (1399, 1403, 1408, etc.).
 */

export interface JalaliDate {
  jy: number;
  jm: number; // 1..12
  jd: number; // 1..31
}

